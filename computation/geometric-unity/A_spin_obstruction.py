import itertools
import numpy as np
import sympy as sp
from clifford77 import clifford_pq


def k1():
    print("=== K1. Lifts of reflection pairs in Spin(7,7) (real Cl(7,7), 128 x 128, exact integers) ===")
    pos, neg = clifford_pq(7)
    G = [g.astype(np.int64) for g in pos + neg]          # 0..6 square +1, 7..13 square -1
    I = np.eye(G[0].shape[0], dtype=np.int64)
    sq = {}
    for a, b in itertools.combinations(range(14), 2):
        M = G[a] @ G[b]
        M2 = M @ M
        s = 1 if np.array_equal(M2, I) else (-1 if np.array_equal(M2, -I) else None)
        kind = 'pp' if b < 7 else ('nn' if a >= 7 else 'pn')
        sq.setdefault(kind, set()).add(s)
    for kind, label in [('pp', 'both positive (inside E+)'), ('nn', 'both negative (inside E-)'),
                        ('pn', 'one positive, one negative')]:
        print(f"  (g_a g_b)^2 for a,b {label:28s}: {sorted(sq[kind])}")
    alpha = 1 if sq['pp'] == {-1} else 0
    beta = 1 if sq['nn'] == {-1} else 0
    eps = 1 if sq['pn'] == {-1} else 0
    print(f"  => preimage of <r_ab> is Z4 for pp, nn and Z2 x Z2 for pn; restrictions of o: {alpha}, {beta}, {eps}")
    print(f"  => o = {alpha}*w2(E+) + {beta}*w2(E-) + {eps}*w1^2   (Karoubi: o = w2(E+) + w2(E-))")
    print(f"  => in terms of E = E+ (+) E-: o = w2(E) + w1(E+) w1(E-)   [w2(E) = w2(E+) + w2(E-) + w1(E+) w1(E-)]")
    return (alpha, beta, eps) == (1, 1, 0)


def mod2(expr, gens):
    p = sp.Poly(sp.expand(expr), *gens)
    return sp.Poly.from_dict({m: c % 2 for m, c in p.terms() if c % 2}, *gens) if p.terms() else sp.Poly(0, *gens)


def degree_part(expr, gens, d):
    p = mod2(expr, gens)
    return sum((c * sp.prod([v ** k for v, k in zip(gens, m)]) for m, c in p.terms() if sum(m) == d), sp.Integer(0))


def k2():
    print("\n=== K2. Stiefel-Whitney classes of C+ and C- (splitting principle, mod 2) ===")
    t, s1, s2, s3 = sp.symbols('t s1 s2 s3')   # w1 of l and of the line summands of Sigma (duals have equal classes)
    gens = (t, s1, s2, s3)
    s = (s1, s2, s3)
    w_sym2_sigma = sp.prod([1 + s[i] + s[j] for i in range(3) for j in range(i + 1, 3)])   # L_i^2 trivial
    w_Cp = w_sym2_sigma * (1 + t)                       # Sym^2_0 Sigma (w = w(Sym^2 Sigma)) + R + l*
    w_Cm = sp.prod([1 + t + si for si in s]) * sp.prod([1 + si for si in s])   # R g + l*(x)Sigma* + Sigma*
    w_X = (1 + t) * sp.prod([1 + si for si in s])       # pi^* TX = l (+) Sigma
    w1p, w1m = degree_part(w_Cp, gens, 1), degree_part(w_Cm, gens, 1)
    w2p, w2m = degree_part(w_Cp, gens, 2), degree_part(w_Cm, gens, 2)
    w1X, w2X = degree_part(w_X, gens, 1), degree_part(w_X, gens, 2)
    print(f"  w1(C+) = {w1p};  w1(C-) = {w1m};  w1(l) = t,  w1(X) = {w1X}")
    o = w2p + w2m
    ok1 = mod2(o - (w2X + t ** 2), gens).is_zero
    w2C = w2p + w2m + w1p * w1m
    ok2 = mod2(w2C - w2X, gens).is_zero
    ok3 = mod2(w1p - t, gens).is_zero and mod2(w1m - t, gens).is_zero
    print(f"  w1(C+) = w1(C-) = w1(l): {ok3}")
    print(f"  o = w2(C+) + w2(C-) == w2(X) + w1(l)^2 (mod 2): {ok1}")
    print(f"  w2(C) = w2(C+) + w2(C-) + w1(C+) w1(C-) == w2(X) (agrees with fiber_signature.out A7): {ok2}")
    print("  Base (3,1) with c_V c_H < 0, and the overall sign flip (c_V, c_H) -> (-c_V, -c_H), swap or relabel C+ and C-;")
    print("  o and w1(C+-) are symmetric under C+ <-> C-, so the result holds in every (7,7) case of Theorem A4.")
    return ok1 and ok2 and ok3


def k3():
    print("\n=== K3. Exact Gram check of the decomposition C+- at g = eta = diag(+1,-1,-1,-1), c_V = c_H = 1 ===")
    eta = sp.diag(1, -1, -1, -1)
    gi = eta.inv()

    def E(i, j):
        M = sp.zeros(4, 4)
        M[i, j] += 1
        M[j, i] += 1 if i != j else 0
        return M

    S0 = [E(1, 1) - E(2, 2), E(2, 2) - E(3, 3), E(1, 2), E(1, 3), E(2, 3)]     # Sym^2_0 Sigma*
    Mx = [E(0, 1), E(0, 2), E(0, 3)]                                             # l* (x) Sigma*
    gl, gS = E(0, 0), -(E(1, 1) + E(2, 2) + E(3, 3))                            # trace plane; g = gl + gS
    ok = True
    for lam in [sp.Rational(3, 10), sp.Rational(1, 2), sp.Integer(1), sp.Integer(3)]:
        G = lambda h, k: (gi * h * gi * k).trace() - lam * (gi * h).trace() * (gi * k).trace()
        gram = lambda B: sp.Matrix([[G(a, b) for b in B] for a in B])
        g = gl + gS
        perp = G(g, g) * gl - G(g, gl) * g                   # G-orthogonal complement of g in the trace plane
        blocks = {'Sym^2_0 Sigma*': S0, 'l* (x) Sigma*': Mx, 'R g': [g], 'R g^perp (trace plane)': [perp]}
        sig = {}
        for name, B in blocks.items():
            ev = gram(B).eigenvals()
            sig[name] = (sum(m for v, m in ev.items() if v > 0), sum(m for v, m in ev.items() if v < 0))
        cross = all(G(a, b) == 0 for (n1, B1), (n2, B2) in itertools.combinations(blocks.items(), 2)
                    for a in B1 for b in B2)
        lsig = (1, 0) if gi[0, 0] > 0 else (0, 1)
        Ssig = (sum(1 for i in (1, 2, 3) if gi[i, i] > 0), sum(1 for i in (1, 2, 3) if gi[i, i] < 0))
        tot = (sum(v[0] for v in sig.values()) + lsig[0] + Ssig[0], sum(v[1] for v in sig.values()) + lsig[1] + Ssig[1])
        good = (sig == {'Sym^2_0 Sigma*': (5, 0), 'l* (x) Sigma*': (0, 3), 'R g': (0, 1), 'R g^perp (trace plane)': (1, 0)}
                and cross and lsig == (1, 0) and Ssig == (0, 3) and tot == (7, 7))
        ok &= good
        print(f"  lambda = {str(lam):5s}: V-blocks {sig}; mutually G-orthogonal: {cross}; "
              f"H*: l* {lsig}, Sigma* {Ssig}; total {tot}; matches C+ = Sym^2_0+R g^perp+l*, C- = R g+l*Sigma*+Sigma*: {good}")
    return ok


def k4():
    print("\n=== K4. An RP^2 inside one fiber of Met_(1,3) on which the time line is tautological ===")
    print("  g_u = -I + 2 u u^T, u a unit vector in span(e0,e1,e2); g_u = g_{-u}, so u -> g_u factors through RP^2.")
    ok = True
    for u in [(1, 0, 0), (sp.Rational(3, 5), sp.Rational(4, 5), 0), (sp.Rational(2, 3), sp.Rational(2, 3), sp.Rational(1, 3)),
              (0, sp.Rational(5, 13), sp.Rational(12, 13))]:
        v = sp.Matrix(list(u) + [0])
        g = -sp.eye(4) + 2 * v * v.T
        ev = g.eigenvals()
        lor = ev == {1: 1, -1: 3}
        tl = (g * v == v)          # u spans the positive eigenline
        ok &= lor and tl and (-sp.eye(4) + 2 * (-v) * (-v).T == g)
        print(f"  u = {tuple(u)}: eigenvalues {ev} (Lorentzian (1,3): {lor}); time line = R u: {tl}")
    print("  So l restricted to this RP^2 is the tautological line gamma, and w1(l)^2 = w1(gamma)^2 != 0 in H^2(RP^2; Z2).")
    print("  pi^* w2(X) restricts to 0 on a fiber. Hence o = pi^* w2(X) + w1(l)^2 != 0 on Met(X), for every X.")
    print("  On the time-oriented Y' (draft (3.33)) l is oriented, w1(l) = 0, and o = pi^* w2(X).")
    return ok


